"""Generate BrandIconData.g.cs from a simple-icons checkout.

The icons are CC0 (see NOTICE-brand-icons.md); the trademarks are not, which is why the set is
curated by hand rather than swept in wholesale. Microsoft's marks, Slack and a few others are
deliberately absent upstream - their owners asked for removal - so those rows keep their category
glyph instead.

    python tools/make-brand-icons.py --icons <path>/simple-icons/icons \
        --out src/UltimateUpdater/Services/BrandIconData.g.cs
"""

import argparse
import re
import sys
from pathlib import Path

# Curated: things a Windows user plausibly has installed, plus the update sources themselves.
SLUGS = [
    "7zip", "adobephotoshop", "amd", "audacity", "autodesk", "battledotnet", "blender", "brave",
    "ccleaner", "chocolatey", "davinciresolve", "discord", "docker", "dotnet", "ea", "epicgames",
    "figma", "filezilla", "firefox", "gimp", "git", "github", "gnubash", "go", "godotengine",
    "gogdotcom", "googlechrome", "homebrew", "inkscape", "intellijidea", "intel", "itchdotio",
    "krita", "kubernetes", "libreoffice", "malwarebytes", "mysql", "neovim", "nginx", "nodedotjs",
    "notepadplusplus", "npm", "nvidia", "obsstudio", "openjdk", "opera", "php", "postgresql",
    "postman", "pycharm", "python", "qbittorrent", "redis", "riotgames", "rockstargames", "ruby",
    "rust", "signal", "spotify", "steam", "sublimetext", "telegram", "terraform", "thunderbird",
    "torbrowser", "ubisoft", "unity", "virtualbox", "vivaldi", "vlcmediaplayer", "whatsapp",
    "wireshark", "zoom",
    # Packages, not applications: npm/pip/PSGallery rows have no icon on disk to find, so these are
    # the only ones those rows can ever get.
    "angular", "django", "eslint", "flask", "jupyter", "numpy", "pandas", "pnpm", "poetry",
    "prettier", "pytest", "pytorch", "react", "tensorflow", "typescript", "vite", "vuedotjs",
    "webpack", "yarn",
]

PATH_PATTERN = re.compile(r'<path[^>]*\sd="([^"]+)"')
TITLE_PATTERN = re.compile(r"<title>([^<]+)</title>")

HEADER = """// <auto-generated>
//     Generated by tools/make-brand-icons.py from the Simple Icons set (CC0-1.0).
//     Do not edit by hand - re-run the script instead. Licensing: NOTICE-brand-icons.md.
// </auto-generated>

namespace UltimateUpdater.Services;

/// <summary>Brand marks as SVG path data on a 24x24 canvas, keyed by Simple Icons slug.</summary>
internal static class BrandIconData
{
    public static readonly IReadOnlyDictionary<string, string> Paths =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
"""

FOOTER = """        };
}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--icons", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    entries = []
    missing = []

    for slug in sorted(set(SLUGS)):
        svg = args.icons / f"{slug}.svg"
        if not svg.exists():
            missing.append(slug)
            continue

        text = svg.read_text(encoding="utf-8")
        path = PATH_PATTERN.search(text)
        title = TITLE_PATTERN.search(text)
        if not path:
            missing.append(slug)
            continue

        entries.append((slug, title.group(1) if title else slug, path.group(1)))

    if not entries:
        print("no icons found - is --icons pointing at the simple-icons icons directory?", file=sys.stderr)
        return 1

    lines = [HEADER]
    for slug, title, data in entries:
        lines.append(f"            // {title}\n")
        lines.append(f'            ["{slug}"] = "{data}",\n')
    lines.append(FOOTER)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(lines), encoding="utf-8", newline="\n")

    print(f"wrote {len(entries)} brand icons to {args.out}")
    if missing:
        print(f"not in this checkout ({len(missing)}): {', '.join(missing)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
